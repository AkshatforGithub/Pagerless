import json, glob, collections, subprocess, datetime
CUTOFF = "20261019-131925"  # a08d634 landed Oct 19 13:19; earlier oom_kill/cpu_spin never injected
JUDGE120 = {"20261019-144938", "20261019-145338"}
rows = []
for f in sorted(glob.glob("results/2*.jsonl")):
    run = f.split("/")[-1][:15]
    for l in open(f):
        r = json.loads(l); r["run"] = run; rows.append(r)

def flags(r):
    fl = []
    if r["fault"] in ("oom_kill", "cpu_spin") and r["run"] < CUTOFF: fl.append("PREFIX")
    if r.get("llm_errors"): fl.append("INFRA")
    if r["run"] in JUDGE120: fl.append("JUDGE120")
    if r.get("injection_failed"): fl.append("INJFAIL")
    return fl

commit = subprocess.run(["git", "rev-parse", "--short", "HEAD"], capture_output=True, text=True).stdout.strip()
out = []
out.append(f"Baseline table generated by make_baseline.py from results/2*.jsonl")
out.append(f"Date: {datetime.date.today()}  Commit: {commit}")
out.append(f"Excluded: PREFIX (oom_kill/cpu_spin before {CUTOFF}), INFRA (llm_errors>0), JUDGE120, INJFAIL")
out.append("")

cells = collections.defaultdict(list)
excluded = []
for r in rows:
    fl = flags(r)
    if fl: excluded.append((r["run"], r["prompt"], r["fault"], int(r["correct"]), "F" if r["forced"] else "-", fl))
    else: cells[(r["prompt"], r["fault"])].append(r)

faults = sorted({r["fault"] for r in rows})
for p in ("v1", "v2"):
    out.append(f"== {p}: per fault (valid attempts: correct/total, F=forced) ==")
    fc = 0
    for f in faults:
        a = cells.get((p, f), [])
        if not a:
            out.append(f"  {f:20s} NO VALID ROW"); continue
        c = sum(x["correct"] for x in a); fo = sum(x["forced"] for x in a)
        if c: fc += 1
        out.append(f"  {f:20s} {c}/{len(a)} correct, {fo} forced")
    allv = [x for f in faults for x in cells.get((p, f), [])]
    n = len(allv)
    if n:
        out.append(f"  faults with >=1 correct valid attempt: {fc}/{len(faults)}")
        out.append(f"  attempts: {sum(x['correct'] for x in allv)}/{n} correct, {sum(x['forced'] for x in allv)}/{n} forced")
        forced = [x for x in allv if x["forced"]]; unf = [x for x in allv if not x["forced"]]
        if forced: out.append(f"  forced attempts correct: {sum(x['correct'] for x in forced)}/{len(forced)}")
        if unf: out.append(f"  unforced attempts correct: {sum(x['correct'] for x in unf)}/{len(unf)}")
        toks = sorted(x["tokens"] for x in allv); secs = sorted(x["seconds"] for x in allv)
        q = lambda s, k: s[min(len(s) - 1, int(k * len(s)))]
        out.append(f"  tokens mean {sum(toks)//n}, p50 {q(toks,.5)}, p95 {q(toks,.95)}; seconds p50 {q(secs,.5)}, p95 {q(secs,.95)}")
    out.append("")

out.append("== excluded rows (run, prompt, fault, correct, forced, flags) ==")
for e in excluded: out.append(f"  {e}")
out.append("")
out.append("Note: 1-3 attempts per cell; results flip between attempts; v2 was written after seeing a v1 failure.")
open("baseline_table.txt", "w").write("\n".join(out) + "\n")
print("\n".join(out))
